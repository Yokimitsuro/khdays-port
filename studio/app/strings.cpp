Language system_language() {
    int count = 0;
    SDL_Locale** locales = SDL_GetPreferredLocales(&count);
    Language found = Language::en;
    if (locales != nullptr) {
        for (int i = 0; i < count && locales[i] != nullptr; ++i) {
            const Language l = language_from_code(locales[i]->language, Language::count);
            if (l != Language::count) {
                found = l;
                break;
            }
        }
        SDL_free(locales);
    }
    return found;
}

