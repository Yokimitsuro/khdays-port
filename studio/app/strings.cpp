const char* tr(Language language, S id) {
    const auto i = static_cast<std::size_t>(id);
    const auto l = static_cast<std::size_t>(language);
    if (i >= static_cast<std::size_t>(S::count))
        return "";
    const char* w = l < 5 ? rows[i].words[l] : nullptr;
    return w != nullptr && w[0] != '\0' ? w : rows[i].words[0];
}

bool translated(Language language, S id) {
    const auto i = static_cast<std::size_t>(id);
    const auto l = static_cast<std::size_t>(language);
    return i < static_cast<std::size_t>(S::count) && l < 5 && rows[i].id == id && rows[i].words[l] != nullptr &&
           rows[i].words[l][0] != '\0';
}

std::string fmt(Language language, S id, std::initializer_list<std::string_view> args) {
    const std::string_view text = tr(language, id);
    std::string out;
    for (std::size_t i = 0; i < text.size(); ++i) {
        if (text[i] == '{' && i + 2 < text.size() && text[i + 2] == '}' && text[i + 1] >= '0' && text[i + 1] <= '9') {
            const auto n = static_cast<std::size_t>(text[i + 1] - '0');
            if (n < args.size())
                out += *(args.begin() + n);
            i += 2;
        } else {
            out += text[i];
        }
    }
    return out;
}

const char* language_code(Language language) {
    const auto l = static_cast<std::size_t>(language);
    return l < 5 ? codes[l] : "en";
}

const char* language_name(Language language) {
    const auto l = static_cast<std::size_t>(language);
    return l < 5 ? names[l] : names[0];
}

Language language_from_code(std::string_view code, Language fallback) {
    for (int l = 0; l < 5; ++l) {
        if (code.size() >= 2 && code.substr(0, 2) == codes[l])
            return static_cast<Language>(l);
    }
    return fallback;
}

