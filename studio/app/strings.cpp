std::string world_name(Language language, std::string_view code) {
    static const std::pair<const char*, S> known[] = {
        {"tt", S::world_tt}, {"aw", S::world_aw}, {"he", S::world_he}, {"al", S::world_al}, {"eh", S::world_eh},
        {"nm", S::world_nm}, {"zz", S::world_zz}, {"pp", S::world_pp}, {"bb", S::world_bb}, {"tw", S::world_tw},
    };
    for (const auto& [c, id] : known)
        if (code == c)
            return tr(language, id);
    if (code == "hb" || code == "pi")  // in the game's table, without their archives
        return fmt(language, S::world_unshipped, {code});
    return std::string(code);
}

