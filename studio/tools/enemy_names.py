"""The enemies' names by the id a mission's enemy table gives them, from the pinned decompilation (the
id's overlay through data_ov107_020cb6a4, named after its enemy), into
studio/core/missions/enemy_names.cpp and, for the mods' enemies.kinds(), port/runtime/scripts/enemy_names.c
(both committed; docs/FORMATS.md, "Missions").
    python studio/tools/enemy_names.py"""

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DECOMP = ROOT / "external" / "khdays-decomp"
TABLE = DECOMP / "src/overlays/system/ov107_enemy_common/data/ov107_tables_020cb6a0.c"
ENEMIES = DECOMP / "src/overlays/enemies"
OUT = ROOT / "studio" / "core" / "missions" / "enemy_names.cpp"
OUT_C = ROOT / "port" / "runtime" / "scripts" / "enemy_names.c"


def main() -> None:
    src = TABLE.read_text(encoding="utf-8")
    body = src[src.index("data_ov107_020cb6a4[") :]
    numbers = [int(x) for x in re.findall(r"\d+", body[body.index("{") : body.index("}")])]
    assert len(numbers) % 6 == 0, len(numbers)
    overlays = {}
    for d in ENEMIES.iterdir():
        m = re.match(r"ov(\d+)_enemy_(.+)", d.name)
        if m:
            overlays[int(m.group(1))] = m.group(2)
    names = []
    for i in range(len(numbers) // 6):
        columns = [b for b in numbers[6 * i : 6 * i + 6] if b != 255]
        name = overlays.get(114 + columns[0]) if columns else None
        if name is not None:
            name = re.sub(r"_\d+$", "", name)  # a variant of the same enemy
            name = " ".join(w.capitalize() for w in name.split("_"))
        names.append(name)
    commit = subprocess.run(
        ["git", "-C", str(DECOMP), "rev-parse", "--short=9", "HEAD"], capture_output=True, text=True
    ).stdout.strip()
    lines = [
        "// Generated by studio/tools/enemy_names.py from the pinned decompilation",
        f"// (khdays-decomp {commit}); do not edit. An id's enemy: row id of",
        "// data_ov107_020cb6a4 (src/overlays/system/ov107_enemy_common/data/ov107_tables_020cb6a0.c),",
        "// its first column b, overlay 113 + b + 1 as the decompilation names it",
        "// (src/overlays/enemies/ov<N>_enemy_<name>).",
        '#include "core/missions/enemy_names.h"',
        "",
        "namespace studio {",
        "",
        "namespace {",
        "",
        "const char* const kNames[] = {",
    ]
    for i, n in enumerate(names):
        lines.append(f"    {'nullptr' if n is None else chr(34) + n + chr(34)},  // {i}")
    lines += [
        "};",
        "",
        "}  // namespace",
        "",
        "const char* enemy_name(int id) {",
        "    if (id < 0 || id >= static_cast<int>(sizeof(kNames) / sizeof(kNames[0]))) return nullptr;",
        "    return kNames[id];",
        "}",
        "",
        "int enemy_ids() { return static_cast<int>(sizeof(kNames) / sizeof(kNames[0])); }",
        "",
        "}  // namespace studio",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    c = [
        "/* Generated by studio/tools/enemy_names.py from the pinned decompilation",
        f" * (khdays-decomp {commit}); do not edit. An id's enemy, as studio/core/missions/enemy_names.cpp",
        " * names it. */",
        "#include <stddef.h>",
        "",
        "static const char *const NAMES[] = {",
    ]
    for i, n in enumerate(names):
        c.append(f"    {'NULL' if n is None else chr(34) + n + chr(34)}, /* {i} */")
    c += [
        "};",
        "",
        "const char *khdays_enemy_name(int id)",
        "{",
        "    return id >= 0 && id < (int)(sizeof(NAMES) / sizeof(NAMES[0])) ? NAMES[id] : NULL;",
        "}",
        "",
    ]
    OUT_C.write_text("\n".join(c), encoding="utf-8", newline="\n")
    for out in (OUT, OUT_C):
        print(f"{out.relative_to(ROOT)}: {sum(1 for n in names if n)} of {len(names)} ids named")


if __name__ == "__main__":
    main()
