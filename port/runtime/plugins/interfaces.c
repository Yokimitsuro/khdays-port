static char *copy(const char *s)
{
    const size_t n = strlen(s) + 1;
    char *c = malloc(n);
    if (c != NULL) {
        memcpy(c, s, n);
    }
    return c;
}

/* Grows `*list` (of `size`-byte entries) to hold one more; 0 out of memory. */
static int room_for_one(void **list, int count, int *room, size_t size)
{
    if (count < *room) {
        return 1;
    }
    const int grown = *room > 0 ? *room * 2 : 8;
    void *bigger = realloc(*list, (size_t)grown * size);
    if (bigger == NULL) {
        return 0;
    }
    *list = bigger;
    *room = grown;
    return 1;
}

static uint64_t next_id = 1;

/* --- Services ------------------------------------------------------------------------------------------------ */

typedef struct Service {
    KhPlugin *owner;
    char *name;
    uint32_t version;
    const void *table;
} Service;

static Service *services;
static int service_count, service_room;

static KhResult publish(KhPlugin *plugin, const char *name, uint32_t version, const void *table)
{
    char text[300];
    if (plugin == NULL || name == NULL || table == NULL || strncmp(name, "kh.", 3) == 0) {
        return KH_ERROR;
    }
    for (int i = 0; i < service_count; ++i) {
        if (strcmp(services[i].name, name) == 0 && services[i].version == version) {
            snprintf(text, sizeof(text), "service %.100s %u not published: %.100s's already", name, version,
                     khdays_plugins_mod_id(services[i].owner));
            khdays_plugins_tell(plugin, text);
            return KH_ERROR;
        }
    }
    if (!room_for_one((void **)&services, service_count, &service_room, sizeof(*services))) {
        return KH_ERROR;
    }
    services[service_count] = (Service){plugin, copy(name), version, table};
    if (services[service_count].name == NULL) {
        return KH_ERROR;
    }
    ++service_count;
    return KH_OK;
}

static void withdraw(KhPlugin *plugin, const char *name, uint32_t version)
{
    for (int i = 0; i < service_count; ++i) {
        if (services[i].owner == plugin && strcmp(services[i].name, name) == 0 && services[i].version == version) {
            free(services[i].name);
            services[i] = services[--service_count];
            return;
        }
    }
}

static const KhServices services_table = {sizeof(KhServices), publish, withdraw};

/* --- Events -------------------------------------------------------------------------------------------------- */

typedef struct Subscription {
    uint64_t id;
    KhPlugin *owner;
    char *name;
    KhEventFunction function;
    void *user;
} Subscription;

static Subscription *subscriptions;
static int subscription_count, subscription_room, delivering;
static int subscriptions_dead; /* marked while delivering */

static KhSubscription subscribe(KhPlugin *plugin, const char *name, KhEventFunction function, void *user)
{
    if (plugin == NULL || name == NULL || function == NULL ||
        !room_for_one((void **)&subscriptions, subscription_count, &subscription_room, sizeof(*subscriptions))) {
        return 0;
    }
    subscriptions[subscription_count] = (Subscription){next_id, plugin, copy(name), function, user};
    if (subscriptions[subscription_count].name == NULL) {
        return 0;
    }
    ++subscription_count; /* a new one is heard from the next event (the walk below counts at its start) */
    return next_id++;
}

static void drop_dead_subscriptions(void)
{
    int kept = 0;
    for (int i = 0; i < subscription_count; ++i) {
        if (subscriptions[i].function != NULL) {
            subscriptions[kept++] = subscriptions[i];
        } else {
#pragma warning(suppress : 6001) /* the entries up to subscription_count are subscribe()'s, each name set */
            free(subscriptions[i].name);
        }
    }
    subscription_count = kept;
    subscriptions_dead = 0;
}

static void unsubscribe(KhPlugin *plugin, KhSubscription subscription)
{
    for (int i = 0; i < subscription_count; ++i) {
        if (subscriptions[i].id == subscription && subscriptions[i].owner == plugin) {
            subscriptions[i].function = NULL;
            subscriptions_dead = 1;
        }
    }
    if (delivering == 0 && subscriptions_dead) {
        drop_dead_subscriptions();
    }
}

static void deliver(const KhEvent *event)
{
    const int count = subscription_count;
    ++delivering;
    for (int i = 0; i < count; ++i) {
        /* the list may grow (moved) while a callback runs: read the entry anew each time */
        if (subscriptions[i].function != NULL && strcmp(subscriptions[i].name, event->name) == 0) {
            KhPlugin *was = khdays_plugins_calling(subscriptions[i].owner);
            subscriptions[i].function(event, subscriptions[i].user);
            khdays_plugins_calling(was);
        }
    }
    if (--delivering == 0 && subscriptions_dead) {
        drop_dead_subscriptions();
    }
}

void khdays_plugins_deliver(const char *name, uint32_t version, const void *data, uint32_t size)
{
    KhEvent event;
    memset(&event, 0, sizeof(event));
    event.size = sizeof(event);
    event.name = name;
    event.a = version;
    event.data = data;
    event.data_size = size;
    deliver(&event);
}

static KhResult raise_event(KhPlugin *plugin, const char *name, const void *data, uint32_t size)
{
    KhEvent event;
    if (plugin == NULL || name == NULL || strchr(name, '.') == NULL || strncmp(name, "kh.", 3) == 0 ||
        !khdays_plugins_on_game_thread()) {
        return KH_ERROR;
    }
    memset(&event, 0, sizeof(event));
    event.size = sizeof(event);
    event.name = name;
    event.data = data;
    event.data_size = size;
    deliver(&event);
    return KH_OK;
}

static const KhEvents events_table = {sizeof(KhEvents), subscribe, unsubscribe, raise_event};

int khdays_plugins_listening(void)
{
    return subscription_count > 0;
}

void khdays_plugins_game_event(const char *name, long long a, long long b, long long c, long long d, const char *text)
{
    KhEvent event;
    if (subscription_count == 0) {
        return;
    }
    memset(&event, 0, sizeof(event));
    event.size = sizeof(event);
    event.name = name;
    event.a = a;
    event.b = b;
    event.c = c;
    event.d = d;
    event.text = text;
    deliver(&event);
}

/* --- Hooks --------------------------------------------------------------------------------------------------- */

typedef struct Hook {
    uint64_t id;
    KhPlugin *owner;
    int point, when;
    int32_t priority;
    uint32_t flags;
    KhHookFunction function; /* NULL: removed while dispatching */
    void *user;
} Hook;

static Hook *hooks;
static int hook_count, hook_room, dispatching, hooks_dead;
static Hook *waiting_hooks; /* added while dispatching */
static int waiting_count, waiting_room;
static int used[KHDAYS_HOOK_POINT_COUNT];

/* The order a point's hooks run in: before-functions highest priority first, after-functions lowest first, then
 * the order they were added. */
static int runs_before(const Hook *a, const Hook *b)
{
    if (a->point != b->point) {
        return a->point < b->point;
    }
    if (a->when != b->when) {
        return a->when < b->when;
    }
    if (a->priority != b->priority) {
        return a->when == KH_HOOK_BEFORE ? a->priority > b->priority : a->priority < b->priority;
    }
    return a->id < b->id;
}

static void insert_hook(const Hook *h)
{
    int at = hook_count;
    if (!room_for_one((void **)&hooks, hook_count, &hook_room, sizeof(*hooks))) {
        return;
    }
    while (at > 0 && runs_before(h, &hooks[at - 1])) {
        hooks[at] = hooks[at - 1];
        --at;
    }
    hooks[at] = *h;
    ++hook_count;
    ++used[h->point];
}

static void settle_hooks(void)
{
    int kept = 0;
    if (hooks_dead) {
        for (int i = 0; i < hook_count; ++i) {
            if (hooks[i].function != NULL) {
                hooks[kept++] = hooks[i];
            }
        }
        hook_count = kept;
        hooks_dead = 0;
    }
    for (int i = 0; i < waiting_count; ++i) {
        insert_hook(&waiting_hooks[i]);
    }
    waiting_count = 0;
}

static int point_of(const char *name)
{
    for (int i = 0; i < KHDAYS_HOOK_POINT_COUNT; ++i) {
        if (strcmp(khdays_hook_points[i].name, name) == 0) {
            return i;
        }
    }
    return -1;
}

static KhHook add_hook(KhPlugin *plugin, const char *point, KhHookWhen when, int32_t priority, uint32_t flags,
                       KhHookFunction function, void *user)
{
    char text[300];
    const int p = point != NULL ? point_of(point) : -1;
    Hook h;
    if (plugin == NULL || function == NULL || (when != KH_HOOK_BEFORE && when != KH_HOOK_AFTER)) {
        return 0;
    }
    if (p < 0) {
        snprintf(text, sizeof(text), "hook not added: no hook point %.100s", point != NULL ? point : "(none)");
        khdays_plugins_tell(plugin, text);
        return 0;
    }
    if ((flags & KH_HOOK_REPLACES) != 0 && when == KH_HOOK_BEFORE) {
        for (int i = 0; i < hook_count; ++i) {
            if (hooks[i].function != NULL && hooks[i].point == p && hooks[i].owner != plugin &&
                (hooks[i].flags & KH_HOOK_REPLACES) != 0) {
                snprintf(text, sizeof(text), "hook %.100s replaces it as %.100s's does: the higher priority goes first",
                         point, khdays_plugins_mod_id(hooks[i].owner));
                khdays_plugins_tell(plugin, text);
            }
        }
    }
    h = (Hook){next_id++, plugin, p, (int)when, priority, flags, function, user};
    if (dispatching > 0) {
        if (room_for_one((void **)&waiting_hooks, waiting_count, &waiting_room, sizeof(*waiting_hooks))) {
            waiting_hooks[waiting_count++] = h;
        }
    } else {
        insert_hook(&h);
    }
    return h.id;
}

static void remove_hook(KhPlugin *plugin, KhHook hook)
{
    for (int i = 0; i < hook_count; ++i) {
        if (hooks[i].id == hook && hooks[i].owner == plugin && hooks[i].function != NULL) {
            hooks[i].function = NULL;
            --used[hooks[i].point];
            hooks_dead = 1;
        }
    }
    for (int i = 0; i < waiting_count; ++i) {
        if (waiting_hooks[i].id == hook && waiting_hooks[i].owner == plugin) {
            waiting_hooks[i] = waiting_hooks[--waiting_count];
            break;
        }
    }
    if (dispatching == 0) {
        settle_hooks();
    }
}

static uint32_t point_count(void)
{
    return KHDAYS_HOOK_POINT_COUNT;
}

static const char *point_name(uint32_t index)
{
    return index < KHDAYS_HOOK_POINT_COUNT ? khdays_hook_points[index].name : NULL;
}

static const char *point_signature(uint32_t index)
{
    return index < KHDAYS_HOOK_POINT_COUNT ? khdays_hook_points[index].signature : NULL;
}

static const KhHooks hooks_table = {sizeof(KhHooks), add_hook, remove_hook, point_count, point_name, point_signature};

int khdays_hook_on(int point)
{
    return point >= 0 && point < KHDAYS_HOOK_POINT_COUNT && used[point] > 0;
}

/* The point's hooks of one kind, in order: each called with `call` (before-functions until one skips). */
static void run_hooks(int point, int when, KhHookCall *call)
{
    const int count = hook_count;
    ++dispatching;
    for (int i = 0; i < count; ++i) {
        KhPlugin *was;
        /* in a room a plugin not made for rooms changes nothing of the game */
        if (hooks[i].point != point || hooks[i].when != when || hooks[i].function == NULL ||
            !khdays_plugins_may_change(hooks[i].owner)) {
            continue;
        }
        was = khdays_plugins_calling(hooks[i].owner);
        hooks[i].function(call, hooks[i].user);
        khdays_plugins_calling(was);
        if (when == KH_HOOK_BEFORE && call->skip) {
            break;
        }
    }
    if (--dispatching == 0) {
        settle_hooks();
    }
}

static void prepare_call(KhHookCall *call, int point, unsigned long long *args, unsigned long long result)
{
    memset(call, 0, sizeof(*call));
    call->size = sizeof(*call);
    call->point = khdays_hook_points[point].name;
    call->arg_count = (uint32_t)khdays_hook_points[point].args;
    call->args = (uint64_t *)args;
    call->result = result;
    call->has_result = khdays_hook_points[point].returns;
}

int khdays_hook_before(int point, unsigned long long *args, unsigned long long *result)
{
    KhHookCall call;
    if (!khdays_hook_on(point)) {
        return 0;
    }
    prepare_call(&call, point, args, *result);
    run_hooks(point, KH_HOOK_BEFORE, &call);
    *result = call.result;
    return call.skip != 0;
}

void khdays_hook_after(int point, unsigned long long *args, unsigned long long *result)
{
    KhHookCall call;
    if (!khdays_hook_on(point)) {
        return;
    }
    prepare_call(&call, point, args, *result);
    run_hooks(point, KH_HOOK_AFTER, &call);
    *result = call.result;
}

/* --- Finding and forgetting ---------------------------------------------------------------------------------- */

const void *khdays_plugins_interface(KhPlugin *plugin, const char *name, uint32_t version)
{
    (void)plugin;
    if (name == NULL) {
        return NULL;
    }
    if (strcmp(name, KH_SERVICES) == 0) {
        return version == KH_SERVICES_VERSION ? &services_table : NULL;
    }
    if (strcmp(name, KH_EVENTS) == 0) {
        return version == KH_EVENTS_VERSION ? &events_table : NULL;
    }
    if (strcmp(name, KH_HOOKS) == 0) {
        return version == KH_HOOKS_VERSION ? &hooks_table : NULL;
    }
    if (strcmp(name, KH_ENGINE) == 0) {
        return version == KH_ENGINE_VERSION ? khdays_plugins_engine() : NULL;
    }
    if (strcmp(name, KH_ACTORS) == 0) {
        return version == KH_ACTORS_VERSION ? khdays_plugins_actors() : NULL;
    }
    if (strcmp(name, KH_NET) == 0) {
        return version == KH_NET_VERSION ? khdays_plugins_net() : NULL;
    }
    if (strcmp(name, KH_PARAMETERS) == 0) {
        return version == KH_PARAMETERS_VERSION ? khdays_plugins_parameters() : NULL;
    }
    if (strcmp(name, KH_COMBAT) == 0) {
        return version == KH_COMBAT_VERSION ? khdays_plugins_combat() : NULL;
    }
    if (strcmp(name, KH_INPUT) == 0) {
        return version == KH_INPUT_VERSION ? khdays_plugins_input() : NULL;
    }
    if (strcmp(name, KH_CHARACTERS) == 0) {
        return version == KH_CHARACTERS_VERSION ? khdays_plugins_characters() : NULL;
    }
    for (int i = 0; i < service_count; ++i) {
        if (strcmp(services[i].name, name) == 0 && services[i].version == version) {
            return services[i].table;
        }
    }
    return NULL;
}

void khdays_plugins_forget(KhPlugin *plugin)
{
    for (int i = service_count - 1; i >= 0; --i) {
        if (services[i].owner == plugin) {
            free(services[i].name);
            services[i] = services[--service_count];
        }
    }
    for (int i = 0; i < subscription_count; ++i) {
        if (subscriptions[i].owner == plugin && subscriptions[i].function != NULL) {
            subscriptions[i].function = NULL;
            subscriptions_dead = 1;
        }
    }
    if (delivering == 0 && subscriptions_dead) {
        drop_dead_subscriptions();
    }
    for (int i = 0; i < hook_count; ++i) {
        if (hooks[i].owner == plugin && hooks[i].function != NULL) {
            hooks[i].function = NULL;
            --used[hooks[i].point];
            hooks_dead = 1;
        }
    }
    for (int i = waiting_count - 1; i >= 0; --i) {
        if (waiting_hooks[i].owner == plugin) {
            waiting_hooks[i] = waiting_hooks[--waiting_count];
        }
    }
    if (dispatching == 0) {
        settle_hooks();
    }
    khdays_plugins_characters_forget(plugin);
    khdays_plugins_input_forget(plugin);
}

static SDL_ThreadID game_thread;

void khdays_plugins_mark_game_thread(void)
{
    game_thread = SDL_GetCurrentThreadID();
}

int khdays_plugins_on_game_thread(void)
{
    return game_thread != 0 && SDL_GetCurrentThreadID() == game_thread;
}
