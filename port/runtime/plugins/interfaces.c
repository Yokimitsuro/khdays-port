/* The port's interfaces for native plugins: services, events and hooks (interfaces.h). Each list keeps the plugin
 * that registered each entry, dropped at its stop. While a list is being walked (an event delivered, a hook point
 * dispatched) an entry removed is only marked, and entries added wait, so that a callback may add and remove. */
